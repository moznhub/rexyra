//! `CONFIG REWRITE` writes the settings in effect to the configuration file,
//! and a server started from that file again has them. This runs the real
//! binary, as only it reads a configuration file.

use std::io::{BufRead, BufReader, Write};
use std::net::{TcpListener, TcpStream};
use std::path::PathBuf;
use std::process::{Child, Command, Stdio};
use std::time::{Duration, Instant};

struct TempDir(PathBuf);

impl TempDir {
    fn new(name: &str) -> TempDir {
        let path =
            std::env::temp_dir().join(format!("rexyra-rewrite-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&path);
        std::fs::create_dir_all(&path).unwrap();
        TempDir(path)
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

struct Server(Child);

impl Drop for Server {
    fn drop(&mut self) {
        let _ = self.0.kill();
        let _ = self.0.wait();
    }
}

fn free_port() -> u16 {
    TcpListener::bind("127.0.0.1:0")
        .unwrap()
        .local_addr()
        .unwrap()
        .port()
}

fn start(config: &PathBuf, port: u16) -> (Server, Client) {
    let mut child = Command::new(env!("CARGO_BIN_EXE_rexyra-server"))
        .arg(config)
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .unwrap();
    let started = Instant::now();
    loop {
        if let Ok(stream) = TcpStream::connect(("127.0.0.1", port)) {
            stream
                .set_read_timeout(Some(Duration::from_secs(10)))
                .unwrap();
            return (Server(child), Client(BufReader::new(stream)));
        }
        if let Some(status) = child.try_wait().unwrap() {
            panic!("the server exited at start-up: {status}");
        }
        assert!(started.elapsed() < Duration::from_secs(10), "no server");
        std::thread::sleep(Duration::from_millis(20));
    }
}

struct Client(BufReader<TcpStream>);

impl Client {
    /// Sends a command and returns the reply flattened to its lines, with
    /// the type markers of simple replies kept.
    fn run(&mut self, args: &[&str]) -> Vec<String> {
        let mut request = format!("*{}\r\n", args.len());
        for arg in args {
            request.push_str(&format!("${}\r\n{arg}\r\n", arg.len()));
        }
        self.0.get_mut().write_all(request.as_bytes()).unwrap();
        let mut out = Vec::new();
        self.read(&mut out);
        out
    }

    fn read(&mut self, out: &mut Vec<String>) {
        let mut line = String::new();
        self.0.read_line(&mut line).unwrap();
        let line = line.trim_end().to_owned();
        match line.as_bytes().first() {
            Some(b'*') => {
                for _ in 0..line[1..].parse::<usize>().unwrap() {
                    self.read(out);
                }
            }
            Some(b'$') if line != "$-1" => {
                let mut value = String::new();
                self.0.read_line(&mut value).unwrap();
                out.push(value.trim_end().to_owned());
            }
            _ => out.push(line),
        }
    }
}

#[test]
fn settings_survive_a_restart_through_the_file() {
    let dir = TempDir::new("restart");
    let config = dir.0.join("rexyra.conf");
    let port = free_port();
    let quoted_dir = rexyra_commands::rewrite::quote(dir.0.to_str().unwrap());
    std::fs::write(
        &config,
        format!(
            "# Kept as it is.\nport {port}\ndir {quoted_dir}\nsave ''\n\
             lua-time-limit 4000\nloglevel notice\n"
        ),
    )
    .unwrap();

    let (server, mut client) = start(&config, port);
    // Nothing changed yet: the lines already there are written back in
    // their usual form and, as every other setting is at its default,
    // only the users are added.
    assert_eq!(client.run(&["CONFIG", "REWRITE"]), ["+OK"]);
    assert_eq!(
        std::fs::read_to_string(&config).unwrap(),
        format!(
            "# Kept as it is.\nport {port}\ndir {quoted_dir}\nsave \"\"\n\
             busy-reply-threshold 4000\nloglevel notice\n\
             \n# Generated by CONFIG REWRITE\n\
             user default on nopass sanitize-payload ~* &* +@all\n"
        )
    );

    for command in [
        &["CONFIG", "SET", "maxmemory", "2gb", "save", "60 5 10 1"][..],
        &["CONFIG", "SET", "maxmemory-policy", "allkeys-lru"],
        &["ACL", "SETUSER", "bob", "on", ">bob's pw", "~k*", "+get"],
        &["CONFIG", "SET", "requirepass", "two words"],
        &["CONFIG", "SET", "notify-keyspace-events", "Elx$"],
    ] {
        assert_eq!(client.run(command), ["+OK"], "{command:?}");
    }
    assert_eq!(client.run(&["CONFIG", "REWRITE"]), ["+OK"]);
    drop(client);
    drop(server);
    let text = std::fs::read_to_string(&config).unwrap();
    assert!(
        text.contains("\nsave 60 5\n") && text.contains("\nsave 10 1\n"),
        "{text}"
    );
    assert!(text.contains("\nnotify-keyspace-events $lxE\n"), "{text}");

    let (_server, mut client) = start(&config, port);
    assert_eq!(client.run(&["AUTH", "two words"]), ["+OK"], "{text}");
    for (name, value) in [
        ("maxmemory", "2147483648"),
        ("maxmemory-policy", "allkeys-lru"),
        ("save", "60 5 10 1"),
        ("busy-reply-threshold", "4000"),
        ("notify-keyspace-events", "$lxE"),
    ] {
        assert_eq!(
            client.run(&["CONFIG", "GET", name]),
            [name, value],
            "{text}"
        );
    }
    assert_eq!(client.run(&["AUTH", "bob", "bob's pw"]), ["+OK"], "{text}");
    assert_eq!(client.run(&["GET", "k1"]), ["$-1"]);
    assert!(client.run(&["SET", "k1", "v"])[0].starts_with("-NOPERM"));
}

#[test]
fn without_a_file_there_is_nothing_to_rewrite() {
    let dir = TempDir::new("none");
    let port = free_port();
    let mut child = Command::new(env!("CARGO_BIN_EXE_rexyra-server"))
        .args(["--port", &port.to_string(), "--save", "", "--dir"])
        .arg(&dir.0)
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .unwrap();
    let started = Instant::now();
    let stream = loop {
        if let Ok(stream) = TcpStream::connect(("127.0.0.1", port)) {
            break stream;
        }
        assert!(started.elapsed() < Duration::from_secs(10), "no server");
        std::thread::sleep(Duration::from_millis(20));
    };
    let mut client = Client(BufReader::new(stream));
    assert_eq!(
        client.run(&["CONFIG", "REWRITE"]),
        ["-ERR The server is running without a config file"]
    );
    let _ = child.kill();
    let _ = child.wait();
}
